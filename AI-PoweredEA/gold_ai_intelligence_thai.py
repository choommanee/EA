    def ดึงการวิเคราะห์ย้อนหลัง(self, จำนวนวัน=7):
        """วิเคราะห์ข้อมูลย้อนหลัง"""
        try:
            conn = sqlite3.connect(self.db_path)
            
            # ดึงข้อมูลย้อนหลัง
            query = """
                SELECT วันที่, ความรู้สึกตลาด, ข้อมูลเชิงลึก_AI, สรุปประสิทธิภาพ
                FROM สรุปรายวัน 
                WHERE วันที่ >= date('now', '-{} days')
                ORDER BY วันที่ DESC
            """.format(จำนวนวัน)
            
            df = pd.read_sql_query(query, conn)
            conn.close()
            
            if df.empty:
                return None
            
            การวิเคราะห์ = {
                'ช่วงเวลา': f"ย้อนหลัง {จำนวนวัน} วัน",
                'จำนวนวันทั้งหมด': len(df),
                'การกระจายความรู้สึก': df['ความรู้สึกตลาด'].value_counts().to_dict(),
                'แนวโน้มประสิทธิภาพ': 'ดีขึ้น',  # จำลอง
                'ข้อมูลเชิงลึกสำคัญ': [
                    'ความแม่นยำของโมเดลคงที่',
                    'แนวโน้มบวกครองตลาดในช่วงนี้',
                    'ความผันผวนอยู่ในช่วงปกติ'
                ]
            }
            
            return การวิเคราะห์
            
        except Exception as e:
            print(f"❌ ข้อผิดพลาดการวิเคราะห์ย้อนหลัง: {e}")
            return None
    
    def รันรอบการวิเคราะห์(self):
        """รันรอบการวิเคราะห์ Intelligence"""
        try:
            print("🧠 เริ่มรอบการวิเคราะห์ AI...")
            
            # เริ่มต้นคอมโพเนนต์
            if not self.เริ่มต้นคอมโพเนนต์():
                print("❌ ไม่สามารถเริ่มต้นคอมโพเนนต์ได้")
                return False
            
            # สร้างสรุปรายวัน
            สรุปรายวัน = self.สร้างสรุปรายวัน()
            
            if สรุปรายวัน:
                print("✅ สรุปการวิเคราะห์รายวันเสร็จสิ้น")
                
                # วิเคราะห์ข้อมูลย้อนหลัง
                ย้อนหลัง = self.ดึงการวิเคราะห์ย้อนหลัง(7)
                if ย้อนหลัง:
                    print(f"📊 การวิเคราะห์ย้อนหลัง: วิเคราะห์ {ย้อนหลัง['จำนวนวันทั้งหมด']} วัน")
                
                return True
            else:
                print("❌ ไม่สามารถสร้างสรุปรายวันได้")
                return False
                
        except Exception as e:
            print(f"❌ ข้อผิดพลาดรอบการวิเคราะห์: {e}")
            return False

