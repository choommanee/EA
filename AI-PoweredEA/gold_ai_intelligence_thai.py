    def บันทึกสรุปรายวัน(self, สรุป):
        """บันทึกสรุปรายวันลงฐานข้อมูล"""
        try:
            conn = sqlite3.connect(self.db_path)
            cursor = conn.cursor()
            
            # บันทึกข่าวสาร
            for ข่าว in สรุป['การวิเคราะห์ข่าว']:
                cursor.execute("""
                    INSERT OR REPLACE INTO การวิเคราะห์ข่าว 
                    (วันที่, หัวข้อ, เนื้อหา, แหล่งข่าว, ความรู้สึก, คะแนนผลกระทบ, ความเกี่ยวข้องทอง, สรุป_AI, เวลาบันทึก)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    สรุป['วันที่'], ข่าว['หัวข้อ'], ข่าว['เนื้อหา'], ข่าว['แหล่งข่าว'],
                    ข่าว['ความรู้สึก'], ข่าว['คะแนนผลกระทบ'], ข่าว['ความเกี่ยวข้องทอง'],
                    ข่าว['สรุป_AI'], ข่าว['เวลาบันทึก']
                ))
            
            # บันทึกสรุปรายวัน
            กรอบการทำงาน = สรุป['กรอบรายวัน']
            cursor.execute("""
                INSERT OR REPLACE INTO สรุปรายวัน 
                (วันที่, ความรู้สึกตลาด, ระดับความผันผวน, จุดสำคัญ, แนวโน้มการเทรด, 
                 ระดับความเสี่ยง, ข้อมูลเชิงลึก_AI, สรุปประสิทธิภาพ, เวลาบันทึก)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                สรุป['วันที่'],
                กรอบการทำงาน['แนวโน้มตลาด'],
                'ปานกลาง',  # จำลอง
                json.dumps(กรอบการทำงาน['จุดสำคัญ'], ensure_ascii=False),
                กรอบการทำงาน['แนวโน้มตลาด'],
                'ปานกลาง',  # จำลอง
                json.dumps(สรุป['ข้อมูลการเรียนรู้'], ensure_ascii=False),
                json.dumps(สรุป['เมตริกประสิทธิภาพ'], ensure_ascii=False),
                สรุป['เวลาบันทึก']
            ))
            
            # บันทึกข้อมูลการเรียนรู้
            ข้อมูลเชิงลึก = สรุป['ข้อมูลการเรียนรู้']
            cursor.execute("""
                INSERT INTO ข้อมูลการเรียนรู้ 
                (วันที่, ประสิทธิภาพโมเดล, แนวโน้มความแม่นยำ, รูปแบบสำคัญ, การปรับตัวตลาด, คำแนะนำ, เวลาบันทึก)
                VALUES (?, ?, ?, ?, ?, ?, ?)
            """, (
                สรุป['วันที่'],
                ข้อมูลเชิงลึก['ประสิทธิภาพโมเดล'],
                ข้อมูลเชิงลึก['แนวโน้มความแม่นยำ'],
                json.dumps(ข้อมูลเชิงลึก['รูปแบบสำคัญ'], ensure_ascii=False),
                ข้อมูลเชิงลึก['การปรับตัวตลาด'],
                json.dumps(ข้อมูลเชิงลึก['คำแนะนำ'], ensure_ascii=False),
                สรุป['เวลาบันทึก']
            ))
            
            conn.commit()
            conn.close()
            
            print("✅ บันทึกสรุปรายวันลงฐานข้อมูลเรียบร้อย")
            
        except Exception as e:
            print(f"❌ ข้อผิดพลาดการบันทึกสรุปรายวัน: {e}")    

