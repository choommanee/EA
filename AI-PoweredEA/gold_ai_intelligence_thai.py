    def สร้างสรุป_AI(self, ข่าว, ความรู้สึก, ผลกระทบ):
        """สร้างสรุป AI จากข่าว"""
        try:
            ข้อความความรู้สึก = "บวก" if ความรู้สึก > 0.2 else "ลบ" if ความรู้สึก < -0.2 else "เป็นกลาง"
            ข้อความผลกระทบ = "สูง" if ผลกระทบ > 0.6 else "ปานกลาง" if ผลกระทบ > 0.3 else "ต่ำ"
            
            สรุป = f"ความรู้สึก{ข้อความความรู้สึก} ({ความรู้สึก:+.2f}) ผลกระทบ{ข้อความผลกระทบ} ({ผลกระทบ:.2f}). "
            
            if ความรู้สึก > 0.3:
                สรุป += "เป็นผลดีต่อราคาทอง แนะนำพิจารณาสถานะซื้อ"
            elif ความรู้สึก < -0.3:
                สรุป += "เป็นผลเสียต่อราคาทอง แนะนำพิจารณาสถานะขายหรือระวัง"
            else:
                สรุป += "สัญญาณผสม ติดตามทิศทางที่ชัดเจนกว่า"
            
            return สรุป
            
        except Exception as e:
            return f"ข้อผิดพลาดการวิเคราะห์: {e}"    

