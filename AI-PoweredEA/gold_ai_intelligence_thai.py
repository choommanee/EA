  def วิเคราะห์ความรู้สึกข่าว(self, ข้อความข่าว):
        """วิเคราะห์ความรู้สึกของข่าว"""
        try:
            # คำสำคัญที่ส่งผลดีต่อทอง
            คำบวก = [
                'เงินเฟ้อ', 'ความไม่แน่นอน', 'วิกฤต', 'สงคราม', 'ความขัดแย้ง',
                'ภาวะถดถอย', 'นโยบายผ่อนคลาย', 'มาตรการกระตุ้น', 'การผ่อนคลายเชิงปริมาณ',
                'ที่หลบภัย', 'ป้องกันความเสี่ยง', 'ความผันผวน', 'หลีกเลี่ยงความเสี่ยง'
            ]
            
            คำลบ = [
                'นโยบายเข้มงวด', 'ขึ้นดอกเบี้ย', 'ดอลลาร์แข็งค่า', 'การฟื้นตัว',
                'การเติบโต', 'ความมั่นใจ', 'เสี่ยงได้', 'การลดมาตรการ',
                'การปกติ', 'การกระชับ', 'ผลตอบแทนขึ้น'
            ]
            
            ข้อความตัวเล็ก = ข้อความข่าว.lower()
            
            คะแนนบวก = sum(1 for คำ in คำบวก if คำ in ข้อความตัวเล็ก)
            คะแนนลบ = sum(1 for คำ in คำลบ if คำ in ข้อความตัวเล็ก)
            
            # คำนวณความรู้สึก (-1 ถึง 1)
            คะแนนรวม = คะแนนบวก + คะแนนลบ
            if คะแนนรวม == 0:
                ความรู้สึก = 0
            else:
                ความรู้สึก = (คะแนนบวก - คะแนนลบ) / คะแนนรวม
            
            # คำนวณคะแนนผลกระทบ (0 ถึง 1)
            คะแนนผลกระทบ = min(คะแนนรวม / 10, 1.0)
            
            # คำนวณความเกี่ยวข้องกับทอง
            คำทอง = ['ทอง', 'โลหะมีค่า', 'xau', 'ทองคำแท่ง', 'เฟด', 'ดอลลาร์', 'เงินเฟ้อ']
            ความเกี่ยวข้องทอง = sum(1 for คำ in คำทอง if คำ in ข้อความตัวเล็ก) / len(คำทอง)
            
            return ความรู้สึก, คะแนนผลกระทบ, ความเกี่ยวข้องทอง
            
        except Exception as e:
            print(f"❌ ข้อผิดพลาดการวิเคราะห์ความรู้สึกข่าว: {e}")
            return 0, 0, 0
    
